def mdot(u, v):
    return -u[..., 0]*v[..., 0] + u[..., 1]*v[..., 1] + u[..., 2]*v[..., 2]

def invariants4(X, Z):
    """X: dict i -> positions [npts, 3];  Z: dict i -> polarisations [npts, ..., 3] (all with the same pol shape)."""
    s = {}
    for (i, j) in ((1, 2), (1, 3), (1, 4), (2, 3), (2, 4), (3, 4)):
        d = X[i] - X[j]; s['s%d%d' % (i, j)] = -mdot(d, d)
    npol = Z[1].ndim - 2
    ex = (slice(None),) + (None,)*npol + (slice(None),)
    z = {}
    for i in (1, 2, 3, 4):
        for j in (1, 2, 3, 4):
            if i != j:
                z['z%d%d' % (i, j)] = mdot(Z[i], (X[j] - X[i])[ex])
    for (i, j) in ((1, 2), (1, 3), (1, 4), (2, 3), (2, 4), (3, 4)):
        z['z%dz%d' % (i, j)] = mdot(Z[i], Z[j])
    return s, z
