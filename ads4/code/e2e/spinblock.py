"""
Exact d = 3 partial waves for <O_1 phi_2 O_3 phi_4>, O_1 = O_3 a conserved current (l = 1) or stress tensor (l = 2),
exchange of a parity-even symmetric traceless (Delta, J), from the differential operators of embed.py acting on
scalar blocks with shifted external dimensions (blocks.py).

   W_diff(P_i; Z_1, Z_3) = sum_{w,w'} c_w c_w'  D_w^{(12)} D_w'^{(34)} [ K^{(w,w')} g^{(w,w')}_{Delta,J}(u,v) ],
   c_w: conservation coefficients (structures.py);  the contribution of O to the correlator is
   lambda_{O_1 phi O}^2 (-1/2)^J W_diff / L_0^2   (standard conserved structure normalised to S_0 coefficient 1).

Real section: all x_ij timelike (s_ij = -x_ij^2 > 0), u, v > 0, z, zbar < 0, non-integer powers of s_ij positive,
g real-analytic (the double-discontinuity phase 2 sin sin stripped).
"""
import os, pickle, itertools
import numpy as np, mpmath as mp, sympy as sp
from embed import word4, Gsyms, D1, D2, D3, D4, Delta as symDelta, J as symJ, cached, JETMAX
from structures import get as get_struct, WORDS, Dphi as symDphi
from blocks import CBlock

_here = os.path.dirname(os.path.abspath(__file__))
SNAMES = ['s12', 's13', 's14', 's23', 's24', 's34']
ZNAMES = ['z12', 'z13', 'z14', 'z31', 'z32', 'z34', 'z1z3']
GKEYS = sorted(Gsyms().keys())

def _phi_expr(l):
    def build():
        out = {}
        for wL in WORDS[l]:
            for wR in WORDS[l]:
                Phi, S, G = word4(wL, wR)
                out[(wL, wR)] = Phi
        return out
    return cached('phi_l%d' % l, build)

_lam_cache = {}
def phi_funcs(l, Dphi):
    """numpy functions Phi^{(w,w')}(s..., z..., G...) for O_1 = O_3 of spin l (dimension l+1), scalars of dimension Dphi.
    The generated source is cached in gen_phi_l{l}_{Dphi}.py (sympy cse + numpy printer)."""
    key = (l, float(Dphi))
    if key in _lam_cache:
        return _lam_cache[key]
    modname = 'gen_phi_l%d_%s' % (l, str(float(Dphi)).replace('.', 'p'))
    fn = os.path.join(_here, modname + '.py')
    names = SNAMES + ZNAMES + ['G_%d_%d' % k for k in GKEYS]
    if not os.path.exists(fn):
        from sympy.printing.numpy import NumPyPrinter
        pr = NumPyPrinter()
        ex = _phi_expr(l)
        dph = sp.nsimplify(Dphi)
        src = ["# generated by spinblock.phi_funcs: do not edit", "import numpy", ""]
        for (wL, wR), e in ex.items():
            e = e.subs({D1: l+1, D2: dph, D3: l+1, D4: dph})
            reps, red = sp.cse(e, optimizations='basic')
            src.append("def phi_%s_%s(%s):" % (wL, wR, ", ".join(names)))
            for sym, sub in reps:
                src.append("    %s = %s" % (sym, pr.doprint(sub)))
            src.append("    return %s" % pr.doprint(red[0]))
            src.append("")
        open(fn, 'w').write("\n".join(src))
    import importlib.util
    spec = importlib.util.spec_from_file_location(modname, fn)
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    fs = {(wL, wR): getattr(mod, 'phi_%s_%s' % (wL, wR)) for wL in WORDS[l] for wR in WORDS[l]}
    _lam_cache[key] = fs
    return fs

# ---------------------------------------------------------------- jets
def _pmul(A, B):
    """truncated product of polynomials in (dU, dV); arrays [..., 5, 5]"""
    out = np.zeros(np.broadcast(A, B).shape, dtype=np.result_type(A, B))
    for i in range(JETMAX+1):
        for j in range(JETMAX+1-i):
            a = A[..., i, j]
            if a.dtype != object and not np.any(a): continue
            for k in range(JETMAX+1-i-j):
                for m in range(JETMAX+1-i-j-k):
                    out[..., i+k, j+m] = out[..., i+k, j+m] + a*B[..., k, m]
    return out

def pq_jets(S, r, A0, E0, vpow=0.0):
    """S[p,k,l] = sum Bt_{n,j} (Delta+n)^k r^n P_j^{(l)}(cosh chi)  (reflected block g^{-a,b}, positive radial coordinates).
    A0 = 1/sqrt(u), E0 = sqrt(v/u)  (cosh L = A0 + E0, cosh chi = E0 - A0).
    Returns Gj[p, i, j] = d_P^i d_Q^j [gt/(4r)^Delta],  P = (log u + log v)/2, Q = (log v - log u)/2."""
    obj = (S.dtype == object)
    one = mp.mpf(1) if obj else 1.0
    npts = S.shape[0]
    fact = [1, 1, 2, 6, 24]
    zero = np.zeros((npts, 5, 5), dtype=object if obj else float)
    if obj: zero[...] = mp.mpf(0)
    dA = zero.copy(); dE = zero.copy()
    for i in range(5):
        for j in range(5-i):
            if i + j > 0:
                dA[:, i, j] = A0*(-one/2)**i*(one/2)**j/(fact[i]*fact[j])      # A = A0 exp((dQ - dP)/2)
        if i > 0:
            dE[:, 0, i] = E0/fact[i]                                             # E = E0 exp(dQ)
    dc = dA + dE; dx = dE - dA
    c0 = (r + one/r)/2; sh = (one/r - r)/2
    f1 = one/sh; f2 = -c0/sh**3; f3 = (2*c0**2 + 1)/sh**5; f4 = -(6*c0**3 + 9*c0)/sh**7
    dc2 = _pmul(dc, dc); dc3 = _pmul(dc2, dc); dc4 = _pmul(dc3, dc)
    e = lambda v: v[:, None, None]
    dL = -(e(f1)*dc + e(f2)*dc2/2 + e(f3)*dc3/6 + e(f4)*dc4/24)
    onep = zero.copy(); onep[:, 0, 0] = one
    powL = [onep, dL]; powX = [onep, dx]
    for _ in range(3):
        powL.append(_pmul(powL[-1], dL)); powX.append(_pmul(powX[-1], dx))
    G = zero.copy()
    for k in range(5):
        for l in range(5-k):
            G = G + e(S[:, k, l]/(fact[k]*fact[l]))*_pmul(powL[k], powX[l])
    if vpow != 0:
        # multiply by v^{vpow} = (E0/A0)^{2 vpow} exp(vpow (dP + dQ))      [v = e^{P+Q}]
        ex = zero.copy()
        for i in range(5):
            for j in range(5-i):
                ex[:, i, j] = (one*vpow)**(i+j)/(fact[i]*fact[j])
        G = _pmul(G, ex)*e((E0/A0)**(2*vpow))
    for i in range(5):
        for j in range(5-i):
            G[:, i, j] = G[:, i, j]*(fact[i]*fact[j])
    return G

def _mpfun(f):
    return np.frompyfunc(f, 1, 1)

class SpinBlock:
    def __init__(self, l, Delta, J, Dphi, N, prec='d'):
        self.l, self.Delta, self.J, self.Dphi, self.N, self.prec = l, float(Delta), int(J), float(Dphi), int(N), prec
        cs, se = get_struct(l)
        sub = {symDelta: sp.nsimplify(Delta), symJ: J, symDphi: sp.nsimplify(Dphi)}
        self.c = {w: mp.mpmathify(str(sp.nsimplify(v.subs(sub)).evalf(40))) for w, v in cs.items()}
        L0 = sum(cs[w]*se[w][0] for w in cs)
        self.L0 = mp.mpmathify(str(sp.nsimplify(L0.subs(sub)).evalf(40)))        # W_diff structure = 2^{-J} L0 * (S_0 + ...)
        self.words = WORDS[l]
        self.phi = phi_funcs(l, Dphi)
        self.blocks = {}
        self.ab = {}
        for wL in self.words:
            for wR in self.words:
                a = -((l + 1 + wL.count('a')) - (Dphi + wL.count('b')))/2
                b = ((l + 1 + wR.count('a')) - (Dphi + wR.count('b')))/2
                self.ab[(wL, wR)] = (a, b)
                if (a, b) not in self.blocks:
                    # reflected block g^{c1,c2}, (c1, c2) = (-a, b).  Its radial coefficients are positive for c1 + c2 >= 0;
                    # for c1 + c2 < 0 they alternate and the sum cancels by many orders of magnitude near the Regge limit, so we
                    # use  g^{c1,c2}(u',v') = v'^{-c1-c2} g^{-c1,-c2}(u',v')  (Euler transformation), v' = 1/v.
                    c1, c2 = -a, b
                    if c1 + c2 >= 0:
                        self.blocks[(a, b)] = (CBlock(Delta, J, c1, c2, N, prec=prec), 0.0)
                    else:
                        self.blocks[(a, b)] = (CBlock(Delta, J, -c1, -c2, N, prec=prec), c1 + c2)

    def eval(self, s, z, r, chi, A0, E0, cut=None):
        """s: dict name -> array [npts]; z: dict name -> array [npts, ...pol]; block coordinates r, chi (s-channel radial, moduli),
        A0 = 1/sqrt(u), E0 = sqrt(v/u).
        Returns (logscale[npts], M[npts, ...pol]) with   s13^{l+1} s24^{Dphi} W_diff = exp(logscale) * M."""
        obj = self.prec == 'q'
        npts = len(r)
        log = _mpfun(mp.log) if obj else np.log
        exp = _mpfun(mp.exp) if obj else np.exp
        Jsign = (-1)**self.J
        jets = {}
        for ab, (blk, vpow) in self.blocks.items():
            S = blk.series(r, chi, sig=+1, kmax=4, lmax=4, cut=cut)
            jets[ab] = pq_jets(S, r, A0, E0, vpow=vpow)
        polshape = z['z12'].shape[1:]
        ex = (slice(None),) + (None,)*len(polshape)
        sargs = [s[n][ex] for n in SNAMES]; zargs = [z[n] for n in ZNAMES]
        tot = 0
        l, Dphi = self.l, self.Dphi
        half = mp.mpf(1)/2 if obj else 0.5
        for (wL, wR), f in self.phi.items():
            d1, d2 = l + 1 + wL.count('a'), Dphi + wL.count('b')
            d3, d4 = l + 1 + wR.count('a'), Dphi + wR.count('b')
            # K relative to the reference K0 = 1/(s12 s34)^{(l+1+Dphi)/2}:  all remaining exponents are (half-)integers
            lK = ((d1-d2)*half*(log(s['s24']) - log(s['s14'])) + (d3-d4)*half*(log(s['s24']) - log(s['s23']))
                  - (d1+d2-l-1-Dphi)*half*log(s['s12']) - (d3+d4-l-1-Dphi)*half*log(s['s34']))
            G = jets[self.ab[(wL, wR)]]
            gargs = [G[:, i, j][ex] for (i, j) in GKEYS]
            val = f(*(sargs + zargs + gargs))
            cc = self.c[wL]*self.c[wR]
            tot = tot + (Jsign*cc if obj else float(Jsign*cc))*exp(lK)[ex]*val
        Dl = mp.mpf(self.Delta) if obj else self.Delta
        logscale = (Dl*log(4*r) + (l+1)*log(s['s13']) + Dphi*log(s['s24'])
                    - (l+1+Dphi)*half*(log(s['s12']) + log(s['s34'])))
        return logscale, tot

# ---------------------------------------------------------------- geometry
def mdot(u, v):
    return -u[..., 0]*v[..., 0] + u[..., 1]*v[..., 1] + u[..., 2]*v[..., 2]

def invariants(x1, x2, x3, x4, z1, z3):
    """positions [npts,3], polarisations [npts, ..., 3] (null).  Returns s, z dictionaries."""
    X = {1: x1, 2: x2, 3: x3, 4: x4}
    s = {}
    for (i, j) in ((1, 2), (1, 3), (1, 4), (2, 3), (2, 4), (3, 4)):
        d = X[i] - X[j]; s['s%d%d' % (i, j)] = -mdot(d, d)
    npol = z1.ndim - 2
    ex = (slice(None),) + (None,)*npol + (slice(None),)
    z = {}
    for j in (2, 3, 4): z['z1%d' % j] = mdot(z1, (X[j] - x1)[ex])
    for j in (1, 2, 4): z['z3%d' % j] = mdot(z3, (X[j] - x3)[ex])
    z['z1z3'] = mdot(z1, z3)
    return s, z

def block_coords_from_uv(s, obj=False):
    """block coordinates from the invariants (moderate cross-ratios only: uses sqrt(u), sqrt(v) directly)."""
    sq = _mpfun(mp.sqrt) if obj else np.sqrt
    ach = _mpfun(mp.acosh) if obj else np.arccosh
    ex = _mpfun(mp.exp) if obj else np.exp
    su = sq(s['s12']*s['s34']/(s['s13']*s['s24'])); sv = sq(s['s14']*s['s23']/(s['s13']*s['s24']))
    A0 = 1/su; E0 = sv/su
    r = ex(-ach(A0 + E0)); chi = ach(E0 - A0)
    return r, chi, A0, E0
