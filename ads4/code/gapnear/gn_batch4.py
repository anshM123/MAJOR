"""
gn_batch4 (GAP_NEARGAP.md §4): writes ads4/ext/jobs_batch4.txt -- the direct n1 nodes at Delta_g = 2000 that the Delta_g = 1000
protocol used for the near-gap states J = 12, 16 (HIGHSPIN §4 + SMALLNU §3.2) and J = 21, 27, 29 (SMALLNU §3.3 / HIGHSPIN §2 /
EXT_FOLD), on the own rows Delta = 2000 + J, at the same x (chart A):
  even J = 12, 16 : full direct row x = 0.025 ... 0.95 (38 nodes, step 0.025)                               [HIGHSPIN §4]
  odd  J = 21, 27, 29 : bulk x = 0.05 ... 0.15 (step 0.0125) + 0.175 ... 0.775 (step 0.025) = 34 nodes  [ext jobs A / SMALLNU]
                        + x = 0.025, 0.0375 (at 2000 the bulk's first node x = 0.05 is at nu ~ 100, not ~ 50 as at 1000)
                        + GK15 edge window [0.8, Lam/m_row], nodes above x = 0.945 skipped (n1 fails there)     [HIGHSPIN §2-§3]
  all five          : small-nu window, n1 at nu = 20, 25, 32.5, 40, 47 (n1 only: the n3 C3H evaluator is broken, EDGE_R finding 4,
                      and the window weight at 2000 is ~ x16 smaller than at 1000)                             [SMALLNU]
  reference zero    : where the Delta_ref = 2e4 reference's leading partial wave vanishes inside the row (x0 < 0.95; J >= 16 at
                      2000), two flanking nodes x0 +- 0.0125 are added (the node nearest x0 is unusable, HIGHSPIN §2.1).
n1's seed is irrelevant (fixed Sobol seeds 2000 + r; EXT_FOLD); 4242 is kept for the format.
Usage: python3 gn_batch4.py [out]   (default ../../ext/jobs_batch4.txt; run once, by hand)
"""
import os, sys
import numpy as np
from scipy.special import eval_jacobi, eval_legendre
from scipy.optimize import brentq
HERE = os.path.dirname(os.path.abspath(__file__))
DREF = 20000.0
GKX = np.array([0.991455371120813, 0.949107912342759, 0.864864423359769, 0.741531185599394, 0.586087235467691,
                0.405845151377397, 0.207784955007898, 0.0])


def mphys(D, J):
    a = D - J - 2.0
    return np.sqrt(a*(a + 2*J + 1))


def lam(Dg):
    return np.sqrt((Dg - 2.0)*(Dg - 1.0))


def Dh(J, t):
    c = 1 - 2*t*t
    return ((1 + c)/2)**4*eval_jacobi(J - 4, 0, 8, c) if J % 2 else eval_legendre(J, c)


def ref_zero_x(J, D):
    ts = np.linspace(1e-5, 0.6, 20000); v = Dh(J, ts)
    i = np.where(np.sign(v[:-1]) != np.sign(v[1:]))[0][0]
    return brentq(lambda t: Dh(J, t), ts[i], ts[i + 1])*mphys(DREF, J)/mphys(D, J)


def gk15(a, b):
    c, h = 0.5*(a + b), 0.5*(b - a)
    return sorted({c + s*h*t for t in GKX for s in ((-1, 1) if t else (1,))})


def nodes(J, Dg=2000, cap=0.945):
    D = Dg + J; m = mphys(D, J)
    groups = []
    if J % 2 == 0:
        xb = [round(0.025*i, 4) for i in range(1, 39)]
        groups.append(('bulk', 'full direct row x = 0.025 ... 0.95 (38)', xb))
    else:
        xb = [round(0.05 + 0.0125*i, 4) for i in range(9)] + [round(0.175 + 0.025*i, 4) for i in range(25)]
        groups.append(('bulk', 'direct bulk row x = 0.05 ... 0.775 (34)', xb))
        groups.append(('blo', 'bulk extension x = 0.025, 0.0375 (nu ~ 50, 76)', [0.025, 0.0375]))
        xe = [x for x in gk15(0.8, lam(Dg)/m) if x <= cap]
        groups.append(('edge', 'GK15 edge window [0.8, %.6f], nodes x <= %.3f (%d of 15)' % (lam(Dg)/m, cap, len(xe)), xe))
    x0 = ref_zero_x(J, D)
    if x0 < 0.95:
        groups.append(('rz', 'reference zero x0 = %.4f: flanking nodes x0 -+ 0.0125' % x0, [round(x0 - 0.0125, 4), round(x0 + 0.0125, 4)]))
    nus = []
    for tag, txt, xs in groups:
        nus.append((tag, txt, [x*m for x in xs]))
    nus.append(('lo', 'small-nu window, n1 at nu = 20, 25, 32.5, 40, 47', [20.0, 25.0, 32.5, 40.0, 47.0]))
    return D, m, x0, nus


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'ext', 'jobs_batch4.txt')
    L = ["# ext/jobs_batch4.txt -- Delta_g = 2000 near-gap direct n1 nodes (GAP_NEARGAP.md §4; generated by code/gapnear/gn_batch4.py).",
         "# Format as jobs.txt: TAG METHOD J DELTA SEED nu1,nu2,...  (nu explicit; x = nu/m(Delta, J)).  n1 only (no n3: EDGE_R finding 4).",
         "# Own rows Delta = 2000 + J (the Delta_g = 2000 twist edges), the x grids of the Delta_g = 1000 protocol (chart A).",
         "# n1 seed irrelevant (fixed Sobol seeds).  Default settings of point.py (HC_ADAPT=1, HC_M=HC_MREF=11, L1_DEG=6).",
         "# Expect failures (replica error > 20 %) for nu/Delta >~ 0.94 (x = 0.95 on the even rows) and possibly at nu = 20 (crystal fold);",
         "# the node nearest a reference zero (rz groups) is noisy by construction -- its flanking nodes are included."]
    tot = 0
    for J in (12, 16, 21, 27, 29):
        D, m, x0, groups = nodes(J)
        L.append(f"# J = {J}: Delta = {D}, m = {m:.4f}, Lam/m = {lam(2000)/m:.6f}, J^2/m = {J*J/m:.3f}, reference zero x0 = {x0:.4f}")
        for tag, txt, nus in groups:
            L.append(f"#   {tag}: {txt} -- {len(nus)} jobs")
            L.append(f"N4_J{J}_{tag}  n1  {J}  {D}  4242  " + ",".join(f"{v:.6f}" for v in nus))
            tot += len(nus)
    L.insert(6, f"# {tot} jobs in all.")
    open(out, 'w').write("\n".join(L) + "\n")
    print("\n".join(L)); print(tot)
