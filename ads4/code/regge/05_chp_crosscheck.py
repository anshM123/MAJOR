r"""Check 5: cross-check of the reading of Dhat_4 (CHP (2.54)) against CHP's own evaluation (4.13)-(4.14):
    D(nu) Pi_{i nu}(L) = Pi |eps|^2 beta_1 [ 1 + (beta_4/beta_1) a(nu, L) ( |n.eps|^2/|eps|^2 - 1/(d-1) ) ],
    a(nu, L) = (h + i nu - 1) [ (1-2h) coth L + h - i nu - 1
                 - 2(h-1)(2h-1) e^{-2L} coth L 2F1(h, h+i nu; i nu+2; e^{-2L}) / ((1 + i nu) 2F1(h-1, h+i nu-1; i nu+1; e^{-2L})) ].
With Dhat_4 = -nabla nabla - (nu^2+(h-1)^2)/(d-1) delta acting on a radial solution Pi of the H_{d-1} equation one gets
    a(nu, L) = -(Pi'' - coth L Pi')/Pi      (any d),
which in d = 3 is  -Q^2-type associated function / Pi, the propagator analogue of  -P^2_{-1/2+i nu}/P_{-1/2+i nu}."""
import mpmath as mp
mp.mp.dps = 25
def Pi(h, nu, rho):
    D = h + 1j*nu
    return mp.pi**(1-h)*mp.gamma(D-1)/(2*mp.gamma(D-h+1))*mp.exp((1-D)*rho)*mp.hyp2f1(h-1, D-1, D-h+1, mp.exp(-2*rho))
def a_CHP(h, nu, L):
    x = mp.exp(-2*L)
    return (h + 1j*nu - 1)*((1-2*h)*mp.coth(L) + h - 1j*nu - 1
            - 2*(h-1)*(2*h-1)*x*mp.coth(L)*mp.hyp2f1(h, h+1j*nu, 1j*nu+2, x)/((1+1j*nu)*mp.hyp2f1(h-1, h+1j*nu-1, 1j*nu+1, x)))
for h in (mp.mpf(3)/2, mp.mpf(2), mp.mpf(3)):
    for (nu, L) in ((mp.mpf('0.8'), mp.mpf('0.7')), (-1j*mp.mpf('1.2'), mp.mpf('1.4'))):
        f = lambda r: Pi(h, nu, r)
        mine = -(mp.diff(f, L, 2) - mp.coth(L)*mp.diff(f, L))/f(L)
        print(f"d={mp.nstr(2*h,2)} nu={mp.nstr(nu,3)} L={mp.nstr(L,2)}:  -(Pi''-coth Pi')/Pi = {mp.nstr(mine, 12)}   CHP (4.14) = {mp.nstr(a_CHP(h, nu, L), 12)}")

