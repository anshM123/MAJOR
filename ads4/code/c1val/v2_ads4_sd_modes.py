#!/usr/bin/env python3
"""
c1val / v2: (anti-)self-duality of linearised AdS4 graviton modes with definite 3d helicity (Euclidean Poincare AdS4).

Input of the ASD-closure lemma (C1_VALUE.md sec. 3): a boundary-to-bulk graviton mode with 3-momentum k and definite 3d
helicity has a purely self-dual or purely anti-self-dual linearised Weyl tensor (Maldacena-Pimentel's statement that W^3
gives only +++ / --- rests on this), and the irregular partner e^{+kz} of the same 3d helicity has the OPPOSITE duality.
The latter is the mechanism by which the normalisability condition (boundary reflection) feeds SD content into the
second-order field generated by two ASD legs.

Setup: ds^2 = (dx1^2+dx2^2+dx3^2+dz^2)/z^2, h_ij = z^-2 gam(z) e^{i k x3} eps_ij, i,j in {x1,x2} (TT, radial gauge),
eps^(+-) = (e1 +- i e2)(e1 +- i e2), gam = (1+kz)e^{-kz} (regular) or (1-kz)e^{+kz} (irregular).
W^(1)_abcd = R^(1)_abcd + (h_ac g_bd + g_ac h_bd - h_ad g_bc - g_ad h_bc)   (on-shell, R_ab = -3 g_ab).
Checks: linearised Einstein equation; W^(1) = s * (*W^(1)) with s = +-1, for each mode.
Writes cache/v2_ads4_sd_modes.txt.
"""
import os, sys, itertools
import sympy as sp

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cache', 'v2_ads4_sd_modes.txt')
lines = []
def log(s=''):
    print(s); lines.append(str(s))

x1, x2, x3, z = sp.symbols('x1 x2 x3 z', real=True)
k = sp.symbols('k', positive=True)
X = [x1, x2, x3, z]
N = 4
gb = sp.diag(*([1/z**2]*4))
gbi = gb.inv()

def christoffel(g, gi):
    return [[[sum(gi[a, e]*(sp.diff(g[e, b], X[c]) + sp.diff(g[e, c], X[b]) - sp.diff(g[b, c], X[e]))
                  for e in range(N))/2 for c in range(N)] for b in range(N)] for a in range(N)]

def riemann_low(g, Gam):
    # R^a_{bcd} = d_c Gam^a_{db} - d_d Gam^a_{cb} + Gam^a_{ce} Gam^e_{db} - Gam^a_{de} Gam^e_{cb}; lower with g
    Rup = {}
    for a, b, c, d in itertools.product(range(N), repeat=4):
        Rup[(a, b, c, d)] = (sp.diff(Gam[a][d][b], X[c]) - sp.diff(Gam[a][c][b], X[d])
                             + sum(Gam[a][c][e]*Gam[e][d][b] - Gam[a][d][e]*Gam[e][c][b] for e in range(N)))
    return {(a, b, c, d): sum(g[a, e]*Rup[(e, b, c, d)] for e in range(N))
            for a, b, c, d in itertools.product(range(N), repeat=4)}

s = sp.symbols('s')
def first_order_weyl(h):
    g = gb + s*h
    gi = gbi - s*gbi*h*gbi
    Gam = christoffel(g, gi)
    R = riemann_low(g, Gam)
    R1 = {key: sp.diff(val, s).subs(s, 0) for key, val in R.items()}
    W = {}
    for a, b, c, d in itertools.product(range(N), repeat=4):
        W[(a, b, c, d)] = sp.simplify(R1[(a, b, c, d)] + h[a, c]*gb[b, d] + gb[a, c]*h[b, d]
                                      - h[a, d]*gb[b, c] - gb[a, d]*h[b, c])
    # first-order Ricci + 3 h (linearised Einstein with Lambda: R_ab + 3 g_ab = 0)
    Ric1 = sp.zeros(N, N)
    # Ricci via R^a_{bad} = g^{ae} R_{ebad}: first order
    for b, d in itertools.product(range(N), repeat=2):
        val = 0
        for a, e in itertools.product(range(N), repeat=2):
            val += sp.diff(gi[a, e]*R[(e, b, a, d)], s).subs(s, 0)
        Ric1[b, d] = sp.simplify(val + 3*h[b, d])
    return W, Ric1

def dual(W):
    vol = sp.sqrt(gb.det())   # = z^-4
    D = {}
    for a, b, c, d in itertools.product(range(N), repeat=4):
        val = 0
        for e, f in itertools.product(range(N), repeat=2):
            lc = sp.LeviCivita(a, b, e, f)
            if lc == 0:
                continue
            val += sp.Rational(1, 2)*vol*lc*gbi[e, e]*gbi[f, f]*W[(e, f, c, d)]
        D[(a, b, c, d)] = sp.simplify(val)
    return D

log('v2: duality of linearised AdS4 graviton modes with definite 3d helicity (Euclidean, k along x3)')
allok = True
results = {}
for gname, gam in [('regular (1+kz)e^{-kz}', (1 + k*z)*sp.exp(-k*z)), ('irregular (1-kz)e^{+kz}', (1 - k*z)*sp.exp(k*z))]:
    for hel, sgn in [('+', 1), ('-', -1)]:
        e = sp.Matrix([1, sgn*sp.I])
        h = sp.zeros(4, 4)
        for i in range(2):
            for j in range(2):
                h[i, j] = gam*sp.exp(sp.I*k*x3)*e[i]*e[j]/z**2
        W, Ric1 = first_order_weyl(h)
        eom = all(sp.simplify(Ric1[i, j]) == 0 for i in range(4) for j in range(4))
        Wd = dual(W)
        nz = any(sp.simplify(W[key]) != 0 for key in W)
        sd = all(sp.simplify(W[key] - Wd[key]) == 0 for key in W)
        asd = all(sp.simplify(W[key] + Wd[key]) == 0 for key in W)
        typ = 'SD (W = +*W)' if sd else ('ASD (W = -*W)' if asd else 'MIXED')
        log(f'  {gname:26s} helicity {hel}:  linearised Einstein eq. {eom};  W != 0: {nz};  duality: {typ}')
        results[(gname, hel)] = typ
        allok &= eom and nz and (sd or asd)
# opposite duality between regular and irregular mode of the same 3d helicity
for hel in '+-':
    r, i_ = results[('regular (1+kz)e^{-kz}', hel)], results[('irregular (1-kz)e^{+kz}', hel)]
    opp = r != i_
    log(f'  helicity {hel}: regular {r} vs irregular {i_}: opposite = {opp}')
    allok &= opp
reg_p, reg_m = results[('regular (1+kz)e^{-kz}', '+')], results[('regular (1+kz)e^{-kz}', '-')]
log(f'  regular +/- modes have opposite duality: {reg_p != reg_m}')
allok &= reg_p != reg_m
log(f'ALL CHECKS PASS: {allok}')
with open(OUT, 'w') as fh:
    fh.write('\n'.join(lines) + '\n')
sys.exit(0 if allok else 1)
