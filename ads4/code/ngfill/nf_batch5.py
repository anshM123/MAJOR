"""
nf_batch5 (NEARGAP_FILL.md §4): writes ads4/ext/jobs_batch5.txt -- the direct n1 nodes at Delta_g = 1000 that the HIGHSPIN / SMALLNU /
EXT_FOLD protocol needs to put the near-gap spins J >= 17 that are still [NE + M] (or [M]) under error control, on the own rows
Delta = 1000 + J (the Delta_g = 1000 twist edges):
  odd  J = 17, 19, 25          : bulk x = 0.05 ... 0.15 (step 0.0125) + 0.175 ... 0.775 (step 0.025) = 34 nodes   [ext job A]
                                 + x = 0.025, 0.0375 (blo) + GK15 edge window [0.8, Lam/m_row], nodes x <= 0.945       [HIGHSPIN §2-3]
  even J = 18, 20, 22, 24, 26, 28, 30, 32 : full direct row x = 0.025 ... 0.95 (38 nodes)                           [HIGHSPIN §4]
                                 + the same GK15 edge nodes (so that the edge can be integrated without interpolation)
  all of the above             : small-nu window, n1 at nu = 20, 25, 32.5, 40, 47                                  [SMALLNU; n1 only]
  reference zero               : Delta_ref = 2e4 is hard-wired in hc_points / ext/point.py; where its leading partial wave vanishes
                                 inside the row (x0 < 0.97: J >= 24 at Delta_g = 1000) two flanking nodes x0 -+ 0.0125 are added
                                 (the node nearest x0 is unusable, HIGHSPIN §2.1).
  J = 23, 31 (twist edges, already with a 34-node direct bulk, GK15 edge and window): the two missing pieces of EXT_FOLD §3.2 / batch-2
                                 addendum -- bulk mid-points x = 0.1875 ... 0.7875 (25 nodes: halves the noise of the shape fit per
                                 parameter) and a second GK15 window on [0.9, Lam/m_row] (nodes <= 0.945: the steep end of the edge,
                                 where the [0.8, Lam/m] window's GK - G7 quadrature estimate and the missing-node envelope sit).
n1's seed is irrelevant (fixed Sobol seeds 2000 + r; EXT_FOLD); 4242 is kept for the format.  No n3 (the n3 C3H evaluator is broken,
EDGE_R finding 4).
Usage: python3 nf_batch5.py [out]   (default ../../ext/jobs_batch5.txt; run once, by hand; prints the job count)
"""
import os, sys
import numpy as np
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'gapnear'))
import gn_batch4 as B4            # read-only: mphys, lam, Dh, ref_zero_x, gk15 (pure functions, no I/O at import)

DG = 1000
CAP = 0.945
LO = [20.0, 25.0, 32.5, 40.0, 47.0]
ODD = (17, 19, 25)
EVEN = (18, 20, 22, 24, 26, 28, 30, 32)
FILL = (23, 31)


def groups(J):
    D = DG + J; m = B4.mphys(D, J); xr = B4.lam(DG)/m
    x0 = B4.ref_zero_x(J, D)
    G = []
    if J in FILL:
        G.append(('bmid', 'bulk mid-points x = 0.1875 ... 0.7875 (25)', [round(0.1875 + 0.025*i, 4) for i in range(25)]))
        xe = [x for x in B4.gk15(0.9, xr) if x <= CAP]
        G.append(('edge2', 'second GK15 window [0.9, %.6f], nodes x <= %.3f (%d of 15)' % (xr, CAP, len(xe)), xe))
    else:
        if J % 2:
            xb = [round(0.05 + 0.0125*i, 4) for i in range(9)] + [round(0.175 + 0.025*i, 4) for i in range(25)]
            G.append(('bulk', 'direct bulk row x = 0.05 ... 0.775 (34)', xb))
            G.append(('blo', 'bulk extension x = 0.025, 0.0375', [0.025, 0.0375]))
        else:
            G.append(('bulk', 'full direct row x = 0.025 ... 0.95 (38)', [round(0.025*i, 4) for i in range(1, 39)]))
        xe = [x for x in B4.gk15(0.8, xr) if x <= CAP]
        G.append(('edge', 'GK15 edge window [0.8, %.6f], nodes x <= %.3f (%d of 15)' % (xr, CAP, len(xe)), xe))
        if x0 < 0.97:
            G.append(('rz', 'reference zero x0 = %.4f: flanking nodes x0 -+ 0.0125' % x0, [round(x0 - 0.0125, 4), round(x0 + 0.0125, 4)]))
    out = [(t, s, [x*m for x in xs]) for t, s, xs in G]
    if J not in FILL:
        out.append(('lo', 'small-nu window, n1 at nu = 20, 25, 32.5, 40, 47', LO))
    return D, m, xr, x0, out


if __name__ == '__main__':
    outf = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'ext', 'jobs_batch5.txt')
    L, tot, per = [], 0, {}
    for J in sorted(ODD + EVEN + FILL):
        D, m, xr, x0, G = groups(J)
        L.append(f"# J = {J}: Delta = {D}, m = {m:.4f}, Lam/m = {xr:.6f}, J^2/m = {J*J/m:.3f}, reference (2e4) zero x0 = {x0:.4f}"
                 + ("  [fill: twist edge only]" if J in FILL else ""))
        n = 0
        for tag, txt, nus in G:
            # drop exact duplicates inside one J (GK node coinciding with a bulk node)
            L.append(f"#   {tag}: {txt} -- {len(nus)} jobs")
            L.append(f"N5_J{J}_{tag}  n1  {J}  {D}  4242  " + ",".join(f"{v:.6f}" for v in nus))
            n += len(nus)
        per[J] = n; tot += n
    H = ["# ext/jobs_batch5.txt -- Delta_g = 1000 near-gap direct n1 nodes for the spins J >= 17 still at [NE + M] / [M]",
         "# (NEARGAP_FILL.md §4; generated by ads4/code/ngfill/nf_batch5.py).  Format as jobs.txt: TAG METHOD J DELTA SEED nu1,nu2,...",
         "# (nu explicit; x = nu/m(Delta, J)); one job per nu.  n1 only (no n3: the n3 C3H evaluator is broken, EDGE_R finding 4).",
         "# Own rows Delta = 1000 + J.  n1 seed irrelevant (fixed Sobol seeds).  Default settings of point.py (HC_ADAPT=1, HC_M=HC_MREF=11, L1_DEG=6).",
         "# Expect failures (replica error > 20 %) for nu/Delta >~ 0.94 (x = 0.95 on the even rows) and possibly at nu = 20 (crystal fold);",
         "# the node nearest a reference zero (rz groups) is noisy by construction -- its flanking nodes are included.",
         f"# {tot} jobs in all: " + ", ".join(f"J={J}: {n}" for J, n in per.items()) + ".",
         "# Priority order = file order is by J; to get the lowest spins first run as is.  Estimated cost: ~2.6 min per job on one core",
         f"# (pilot here, nf_b5pilot.py: J = 24 edge node x = 0.888, 2.8 min; J = 13 bulk 1.3-1.4 min; EDGE_R §6: 2.5 min at J = 26) -> ~{tot*2.6/60:.0f} core-h, ~{tot*2.6/60/16:.1f} h on 16 workers (one core per worker, ~0.7 GB each)."]
    open(outf, 'w').write("\n".join(H + L) + "\n")
    print("\n".join(H + L))
