"""t4: where can an (R)-violating rational factor have poles?  (LIGHT_INPUTS.md Sec. 4).

The gamma-normalised C^+ of a superposition of transverse-helicity plane waves carries, per plane wave, the
frame-mode tables M = R + g1 S of SPINNING_E2E.md 4.4 (l = 2, [DV] there).  In C^+ (pres-pres, parity even) the
g1 S parts cancel and the normalisation divides by R_L R_R, so any mismatch between the light Regge density and the
heavy plane-wave structure enters C^+_2 only through ratios of rational functions of nu whose singular points lie at
  zeros of dd_b = nu^2 + (a-b)^2  (b = 5/2, 9/2)   and zeros of the numerators N_a, N_b, (0,0)-numerator,  a = k+5.
We list them for k = 2..5 and check that none sits at the T pole nu^2 = -9/4 (so a (nu^2+9/4)^-2 admixture cannot
be generated by the mode transform; the exchange itself has a simple pole: single H2 propagator).
"""
import sympy as sp
a, x = sp.symbols('a x')        # x = nu^2
Na = 128*a**4 - 1536*a**3 + 128*a**2*x + 6432*a**2 - 512*a*x - 10880*a + 16*x**2 + 616*x + 6297
Nb = 128*a**4 - 2560*a**3 + 128*a**2*x + 19488*a**2 - 1280*a*x - 66880*a + 16*x**2 + 3304*x + 87225
N00 = 128*a**2 - 128*a*x - 800*a + 16*x**2 + 360*x + 1113
print("t4: singular points (in nu^2) of the l=2 M-table entries, a = k+5; T pole at nu^2 = -9/4")
for k in [2, 3, 4, 5]:
    av = k + 5
    print(f" k={k} (a={av}): dd_5/2 zero at nu^2 = {-(av-sp.Rational(5,2))**2}, dd_9/2 zero at {-(av-sp.Rational(9,2))**2}")
    for name, P in [("N_a(2,-2)", Na), ("N_b(2,2)", Nb), ("N(0,0)", N00)]:
        p = sp.Poly(P.subs(a, av), x)
        roots = [sp.nsimplify(r) for r in sp.solve(p, x)]
        val = P.subs({a: av, x: sp.Rational(-9, 4)})
        print(f"    {name}: roots nu^2 = {roots};  value at nu^2=-9/4: {val} ({'nonzero' if val != 0 else 'ZERO'})")
