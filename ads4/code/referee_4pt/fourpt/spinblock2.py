"""
Exact d = 3 partial waves for <O_1 O_2 O_3 O_4>, all four operators conserved of spin l (Delta = l+1), s-channel (12)(34),
exchange of a parity-even (Delta, J), from the differential operators of embed2 acting on scalar blocks with shifted external
dimensions (e2e/blocks.py, radial Casimir recursion).

   Phi^{(w,w')}  :=  D_w^{(12)} D_w'^{(34)} [ K^{(w,w')} g^{(w,w')}_{Delta,J}(u,v) ]  =  (-1)^J Kt^{(w,w')} phi^{(w,w')}(s, z; G)
   W[c_L, c_R]   :=  sum_{w,w'} c_L[w] c_R[w'] Phi^{(w,w')}
c_L, c_R: coefficient vectors on the words (conserved combinations from structures2).  All word pairs are evaluated and their
Fourier modes stored, so that W for any pair of structures follows by contraction.

Real section / numerics exactly as in e2e/spinblock.py (reflected blocks g^{-a,b}(u/v, 1/v), Euler transformation when the
radial coefficients would alternate, jets in (P, Q) = ((log u + log v)/2, (log v - log u)/2)).
"""
import os, sys, importlib.util
import numpy as np, sympy as sp, mpmath as mp
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'e2e'))
from blocks import CBlock                      # noqa: E402
from spinblock import pq_jets, _mpfun         # noqa: E402  (jets up to order 4)
from embed2 import word4, D1, D2, D3, D4, shifts, cached, SN, ZN, Gsyms
from structures2 import words

def jet_order(l):
    return 4*l          # 2l derivative operators at each of the two vertices

def _phi_exprs(l):
    def build():
        out = {}
        for wL in words(l):
            for wR in words(l):
                Phi, S, G = word4(wL, wR, jet_order(l))
                out[(wL, wR)] = Phi.subs({D1: l+1, D2: l+1, D3: l+1, D4: l+1})
        return out
    return cached('phi4_l%d' % l, build)

GKEYS = {l: sorted(Gsyms(jet_order(l)).keys()) for l in (1, 2)}

ZSYMS = [sp.Symbol(n, positive=False) for n in ZN]     # as created in embed2._mk_engine

def _monomials(l):
    """z-monomials of the multilinear (degree l in each Z_i) partial wave, from the symbolic expressions."""
    def build():
        ex = _phi_exprs(l)
        monos = set()
        polys = {}
        for key, e in ex.items():
            P = sp.Poly(e, *ZSYMS)
            d = P.as_dict()
            polys[key] = d
            monos |= set(d.keys())
        return sorted(monos), polys
    return cached('phi4poly_l%d' % l, build)

_mods = {}
def phi_funcs(l):
    """generated numpy code: for each word pair a function of (s..., G...) returning the list of coefficients of the
    z-monomials MONOS (common list).  The partial wave is  sum_m coef_m * prod_k z_k^{e_mk}."""
    if l in _mods:
        return _mods[l]
    modname = 'gen4_l%d' % l
    fn = os.path.join(HERE, 'cache', modname + '.py')
    names = SN + ['G_%d_%d' % k for k in GKEYS[l]]
    monos, polys = _monomials(l)
    if not os.path.exists(fn):
        from sympy.printing.numpy import NumPyPrinter
        pr = NumPyPrinter()
        src = ["# generated by fourpt/spinblock2.phi_funcs: do not edit", "import numpy", "MONOS = %r" % (monos,), ""]
        for (wL, wR), d in polys.items():
            idx = [monos.index(mn) for mn in d]
            exprs = list(d.values())
            reps, red = sp.cse(exprs, optimizations='basic')
            src.append("def phi_%s_%s(%s):" % (wL, wR, ", ".join(names)))
            for sym, sub in reps:
                src.append("    %s = %s" % (sym, pr.doprint(sub)))
            src.append("    return %r, [%s]" % (idx, ", ".join(pr.doprint(r) for r in red)))
            src.append("")
        open(fn, 'w').write("\n".join(src))
    spec = importlib.util.spec_from_file_location(modname, fn)
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    fs = {(wL, wR): getattr(mod, 'phi_%s_%s' % (wL, wR)) for wL in words(l) for wR in words(l)}
    _mods[l] = (fs, mod.MONOS)
    return _mods[l]

class SpinBlock4:
    def __init__(self, l, Delta, J, N, prec='d'):
        self.l, self.Delta, self.J, self.N, self.prec = l, float(Delta), int(J), int(N), prec
        assert jet_order(l) <= 4, "jets beyond order 4 not implemented (e2e.pq_jets)"
        self.words = words(l)
        self.phi = phi_funcs(l)
        self.blocks, self.ab = {}, {}
        Dx = l + 1
        for wL in self.words:
            for wR in self.words:
                s1, s2 = shifts(wL); s3, s4 = shifts(wR)
                a = -((Dx + s1) - (Dx + s2))/2
                b = ((Dx + s3) - (Dx + s4))/2
                self.ab[(wL, wR)] = (a, b)
                if (a, b) not in self.blocks:
                    c1, c2 = -a, b
                    if c1 + c2 >= 0:
                        self.blocks[(a, b)] = (CBlock(Delta, J, c1, c2, N, prec=prec), 0.0)
                    else:
                        self.blocks[(a, b)] = (CBlock(Delta, J, -c1, -c2, N, prec=prec), c1 + c2)

    def eval_coeffs(self, s, r, chi, A0, E0, combos, cut=None):
        """combos: dict name -> (cL, cR) coefficient dicts on the words.  Returns (logscale[npts], {name: C[nmono, npts]}) with
        s13^{l+1} s24^{l+1} W[cL, cR] = exp(logscale) * sum_m C[m] * monomial_m(z)."""
        obj = self.prec == 'q'
        assert not obj
        log, exp = np.log, np.exp
        Jsign = (-1)**self.J
        jets = {}
        for ab, (blk, vpow) in self.blocks.items():
            S = blk.series(r, chi, sig=+1, kmax=4, lmax=4, cut=cut)
            jets[ab] = pq_jets(S, r, A0, E0, vpow=vpow)
        sargs = [s[n] for n in SN]
        l = self.l; Dx = l + 1
        fs, monos = self.phi
        npts = r.size
        out = {name: np.zeros((len(monos), npts)) for name in combos}
        for (wL, wR), f in fs.items():
            wts = {name: cL[wL]*cR[wR] for name, (cL, cR) in combos.items()}
            if all(w == 0 for w in wts.values()):
                continue
            s1, s2 = shifts(wL); s3, s4 = shifts(wR)
            d1, d2, d3, d4 = Dx + s1, Dx + s2, Dx + s3, Dx + s4
            lK = ((d1-d2)*0.5*(log(s['s24']) - log(s['s14'])) + (d3-d4)*0.5*(log(s['s24']) - log(s['s23']))
                  - (d1+d2-2*Dx)*0.5*log(s['s12']) - (d3+d4-2*Dx)*0.5*log(s['s34']))
            G = jets[self.ab[(wL, wR)]]
            gargs = [G[:, i, j] for (i, j) in GKEYS[l]]
            idx, vals = f(*(sargs + gargs))
            pre = Jsign*exp(lK)
            for name, wt in wts.items():
                if wt == 0: continue
                o = out[name]
                for i, v in zip(idx, vals):
                    o[i] += wt*pre*v
        logscale = (self.Delta*log(4*r) + Dx*log(s['s13']) + Dx*log(s['s24']) - Dx*(log(s['s12']) + log(s['s34'])))
        return logscale, out

def monomial_values(monos, z):
    """z: dict of z-invariants [npts, ...pol] -> array [nmono, npts, ...pol]"""
    keys = ZN
    out = []
    for mn in monos:
        v = 1.0
        for k, e in zip(keys, mn):
            if e: v = v*z[k]**e
        out.append(v*np.ones_like(z['z12']))
    return np.array(out)

